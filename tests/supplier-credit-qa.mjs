import assert from 'node:assert/strict';
import {validateExpensePayment,validateExpenseLineAmounts,deductibleExpenseTotal,expenseCostAmount} from '../src/calculations.js';
import {expenseRegisterLines} from '../src/expense-register.js';
const credit={base:-10,vat:21,re:5.2,withholding:0,deductiblePct:100,documentKind:'rectificativa'};
assert.doesNotThrow(()=>validateExpenseLineAmounts(credit));
assert.throws(()=>validateExpenseLineAmounts({...credit,documentKind:'factura'}));
assert.throws(()=>validateExpenseLineAmounts({...credit,vat:-21}));
assert.doesNotThrow(()=>validateExpensePayment(-12.62,-12.62,'pagado','rectificativa'));
assert.doesNotThrow(()=>validateExpensePayment(-12.62,-5,'parcial','rectificativa'));
assert.doesNotThrow(()=>validateExpensePayment(-12.62,0,'pendiente','rectificativa'));
for(const [paid,status] of [[12.62,'pagado'],[-13,'pagado'],[-12.62,'parcial'],[-1,'pendiente']])assert.throws(()=>validateExpensePayment(-12.62,paid,status,'rectificativa'));
assert.throws(()=>validateExpensePayment(-12.62,-12.62,'pagado','factura'));
const invoice={id:'original',accounting_amount:126.2,gross_expense:126.2,fiscal_reviewed:true,management_only:false};
const refund={id:'credit',document_kind:'rectificativa',accounting_amount:-12.62,gross_expense:-12.62,fiscal_reviewed:true,management_only:false};
const lines=[{expense_id:'original',base_amount:100,vat_rate:21,vat_amount:21,re_base:100,re_rate:5.2,re_amount:5.2,irpf_imputable:126.2},{expense_id:'credit',base_amount:-10,vat_rate:21,vat_amount:-2.1,re_base:-10,re_rate:5.2,re_amount:-.52,irpf_imputable:-12.62}];
assert.equal(deductibleExpenseTotal([invoice,refund],lines),113.58);
assert.equal(expenseCostAmount(invoice)+expenseCostAmount(refund),113.58);
const exported=expenseRegisterLines([refund],lines);
assert.equal(exported[0].subtotal,-12.62);assert.equal(exported[0].fields[8],-10);assert.equal(exported[0].fields[10],-2.1);assert.equal(exported[0].fields[13],-.52);
console.log('SUPPLIER CREDIT QA: signed bases, refunds, fiscal cost and exported taxes OK');
