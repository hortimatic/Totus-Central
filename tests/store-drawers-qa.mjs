import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({locale:'es-ES'});
const errors=[],steps=[];
page.on('pageerror',e=>errors.push(e.message));
const get=()=>page.evaluate(()=>({stores:window.__mockDb.ops_stores,drawers:window.__mockDb.ops_cash_drawers}));
const press=async (action,id)=>page.locator('[data-action="'+action+'"]'+(id?'[data-id="'+id+'"]':'')).first().click();
try{
 await page.goto('http://127.0.0.1:4173/tests/app-mock.html',{waitUntil:'networkidle'});
 await page.locator('#nav [data-route="administracion"]').click();
 await page.locator('[data-action="admin-section"][data-section="negocio"]').first().click();
 assert(await page.locator('#cfgBusiness').count()===1,'No está visible la ficha del negocio');
 await press('store-new');
 await page.locator('#stName').fill('Almacén QA');
 await page.locator('#stCode').fill('TEST_STORE');
 await page.locator('#stAddress').fill('Calle Laboratorio 3');
 await press('store-save');
 let r=await get();const store=r.stores.find(x=>x.code==='TEST_STORE');
 assert(store?.name==='Almacén QA'&&store.address==='Calle Laboratorio 3','El establecimiento no se guardó');
 steps.push('alta establecimiento');
 await press('store-new');
 await page.locator('#stName').fill('Duplicado');
 await page.locator('#stCode').fill('test_store');
 await press('store-save');
 assert((await get()).stores.filter(x=>x.code==='TEST_STORE').length===1,'No se rechazó código repetido');
 await page.locator('#modalHost .close-btn').click();
 await page.getByRole('heading',{name:'Cambios sin guardar',exact:true}).waitFor();await page.locator('[data-confirm="accept"]').click();
 steps.push('rechazo duplicado');
 await press('store-edit',store.id);
 await page.locator('#stName').fill('Almacén QA corregido');
 await press('store-save');
 r=await get();assert(r.stores.find(x=>x.id===store.id).name==='Almacén QA corregido','No se editó tienda');
 steps.push('edición establecimiento');
 const n=page.locator('[data-action="drawer-new"][data-store="'+store.id+'"]');
 assert(await n.count()===1,'No se pueden añadir cajas a la nueva tienda');
 await n.click();
 await page.locator('#drName').fill('Caja QA auxiliar');
 await page.locator('#drCode').fill('TEST_DRAWER');
 await press('drawer-save');
 r=await get();const drawer=r.drawers.find(x=>x.store_id===store.id&&x.code==='TEST_DRAWER');
 assert(drawer?.name==='Caja QA auxiliar','No se guardó caja nueva');
 steps.push('alta de caja');
 await page.locator('[data-action="drawer-edit"][data-id="'+drawer.id+'"]').click();
 await page.locator('#drName').fill('Caja QA corregida');
 await page.locator('#drActive').uncheck();
 await press('drawer-save');
 r=await get();
 assert(r.drawers.find(x=>x.id===drawer.id).name==='Caja QA corregida','No se editó nombre de caja');
 assert(r.drawers.find(x=>x.id===drawer.id).active===false,'No se desactivó caja');
 steps.push('editar y desactivar caja');
 await page.locator('[data-action="drawer-new"][data-store="'+store.id+'"]').click();
 await page.locator('#drName').fill('Caja duplicada');
 await page.locator('#drCode').fill('test_drawer');
 await press('drawer-save');
 assert((await get()).drawers.filter(x=>x.store_id===store.id&&x.code==='TEST_DRAWER').length===1,'Se guardó código de caja duplicado');
 await page.locator('#modalHost .close-btn').click();
 await page.getByRole('heading',{name:'Cambios sin guardar',exact:true}).waitFor();await page.locator('[data-confirm="accept"]').click();
 steps.push('rechazo caja repetida');
 await press('store-edit',store.id);
 await page.locator('#stActive').uncheck();
 await press('store-save');
 assert((await get()).stores.find(x=>x.id===store.id).active===false,'No se desactivó establecimiento');
 steps.push('desactivar establecimiento');
 assert(!errors.length,errors.join('; '));
 console.log('STORE DRAWERS QA: '+steps.join(' | ')+' OK');
}finally{await browser.close()}
