import assert from 'node:assert/strict';
import {planStorage} from '../src/storage-planning.js';
const MB=1048576;
const sizes=[80,45,45,25,7,7,6,6,6,.1];
const runs=sizes.map((size,i)=>({id:String(i),size_bytes:size*MB,status:'success',storage_path:'a/'+i,started_at:new Date(Date.UTC(2026,9,20-i)).toISOString()}));
const reference={plan:'Free',checked_at:'2026-10-20',planning_sample_months:9,planning_sample_files_bytes:80*MB,planning_sample_full_backup_bytes:80*MB,files_limit_bytes:1024*MB};
const saved=sizes.reduce((a,b)=>a+b,0)*MB;
const usage={status:'ok',documents_bytes:79*MB,assets_bytes:MB,all_buckets_bytes:80*MB+saved+55*MB};
const current=planStorage({usage,reference,runs,keep:10});
assert(current.available&&current.days>0&&current.days<30,'Must model replacing partial historical backups with ten current full archives');
assert.equal(current.reason,'space');
assert.equal(current.fullCopiesBytes,800*MB);
assert.equal(current.monthlyOriginalBytes,80*MB/9);
assert.equal(current.downloadableOlderCount,9);
const pinned=planStorage({usage,reference,runs,keep:10,protectedPaths:['a/1']});
assert.equal(pinned.downloadableOlderCount,8);
assert.equal(pinned.downloadableOlderBytes,current.downloadableOlderBytes-45*MB);
assert(!planStorage({usage,reference:{...reference,planning_sample_months:0},runs}).available);
assert(!planStorage({usage:{...usage,status:'error'},reference,runs}).available);
assert(!planStorage({usage:{...usage,all_buckets_bytes:MB},reference,runs}).available);
const defaultFive=planStorage({usage,reference,runs});
assert.equal(defaultFive.keep,5);
assert.equal(defaultFive.fullCopiesBytes,400*MB);
assert(defaultFive.days>current.days,'Five copies must extend the forecast');
const limited=planStorage({usage,reference,runs,keep:3});
assert.equal(limited.reason,'archive','A lower retention must not hide the separate 96 MB archive limit');
const noFailures=planStorage({usage,reference,runs:[...runs,{status:'failed',size_bytes:10000*MB}],keep:10});
assert.equal(noFailures.days,current.days);
const zeroLimit=planStorage({usage,reference:{...reference,files_limit_bytes:0},runs});
assert.equal(zeroLimit.available,false);
const nextUpload=planStorage({usage:{...usage,all_buckets_bytes:1020*MB},reference,runs,keep:10});
assert.equal(nextUpload.days,1,'Need room for new archive before deleting the oldest');
console.log('STORAGE PLANNING QA: nine-month baseline, rolling ten copies, upload peak, protected downloads, missing data and separate archive cap OK');

const migratedUsage={...usage,documents_bytes:0,all_buckets_bytes:usage.all_buckets_bytes-usage.documents_bytes};
const migrated=planStorage({usage:migratedUsage,reference,runs,keep:3,activeOriginalBytes:80*MB});
assert.equal(migrated.currentCopyBytes,80*MB,'Moving originals to OneDrive must not shrink the size of a complete backup');
assert.equal(migrated.days,limited.days,'The technical archive limit must remain visible after migration');
assert.equal(migrated.currentFilesBytes,migratedUsage.all_buckets_bytes,'Remote originals must not be counted as physical Supabase usage');
assert.equal(planStorage({usage:migratedUsage,reference,runs,activeOriginalBytes:-1}).available,false);

const cloudRuns=runs.slice(0,2).map(r=>({...r,storage_provider:'onedrive'}));
const cloudPlan=planStorage({usage:{...usage,documents_bytes:0,assets_bytes:MB,all_buckets_bytes:35*MB},reference,runs:cloudRuns,activeOriginalBytes:80*MB});
assert.equal(cloudPlan.available,true,'Remote full archives must not count as physical Supabase bytes');
assert.equal(cloudPlan.remoteBackups,true);
assert.equal(cloudPlan.retainedBytes,0);
assert.equal(cloudPlan.otherBackupBytes,34*MB);
assert.equal(cloudPlan.currentCopyBytes,80*MB,'The full archive must still include originals located in OneDrive');
assert.equal(cloudPlan.reason,'archive','Remote capacity must never hide the recovery archive safety cap');
