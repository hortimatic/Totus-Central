create role anon; create role authenticated; create role service_role;
create schema private; create schema auth; create schema cron;
create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
create function private.is_admin() returns boolean language sql stable as $$select false$$;
create function private.is_team_member() returns boolean language sql stable as $$select true$$;
create function private.is_manager() returns boolean language sql stable as $$select false$$;
create table private.totus_ai_config(id int primary key,connection_id uuid,reader_connection_id uuid);
create table private.totus_api_connections(id uuid primary key,actor_email text);
create table public.ops_income_adjustments(id int,created_by uuid);
create table public.ops_tasks(id int,deleted_by text);
create table public.team_members(email text,role text);
create table public.ops_user_permissions(email text);
alter table public.team_members enable row level security;
alter table public.ops_user_permissions enable row level security;
create policy directory_select on public.team_members for select to authenticated using (true);
create policy totus_team_directory_privacy on public.team_members as restrictive for select to authenticated using (private.is_manager() or lower(email)=lower(coalesce(auth.jwt()->>'email','')));
create policy perms_select on public.ops_user_permissions for select to authenticated using (private.is_admin() or (private.is_team_member() and lower(email)=lower(coalesce(auth.jwt()->>'email',''))));
grant usage on schema private,auth to authenticated;
grant all on all tables in schema public to anon,authenticated;
alter default privileges for role postgres in schema public grant all on tables to anon,authenticated;
create table cron.job_run_details(runid bigint primary key,status text,end_time timestamptz);
create table cron.job(jobid bigint generated always as identity primary key,jobname text unique,schedule text,command text);
create function cron.schedule(text,text,text) returns bigint language sql as $$insert into cron.job(jobname,schedule,command) values($1,$2,$3) on conflict(jobname) do update set schedule=excluded.schedule,command=excluded.command returning jobid$$;
