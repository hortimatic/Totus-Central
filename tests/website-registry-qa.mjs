import assert from 'node:assert/strict';
import {createWebsiteRegistry} from '../src/website-registry.js';
import {prestashopStore,storeConnection,prestashopProductImage} from '../src/prestashop-readonly.js';
import {productPhoto,productWebUrl} from '../src/productos-catalog.js';
const site=(key,n,extra={})=>({key,name:key,origin:`https://${key}.example`,connection_id:`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`,status:'active',include_in_totals:true,...extra});
const records=[site('hortimatic',1),site('newoldsmok',2),site('hortimatic-2',3,{include_in_totals:false}),site('future-store',4)];
const registry=createWebsiteRegistry(records);
assert.equal(registry.active().length,4);
assert.equal(registry.destinations('hortimatic').length,3);
assert.deepEqual(registry.totals().map(s=>s.key),['hortimatic','newoldsmok','future-store']);
const profiles=records.map(s=>({id:s.connection_id,name:'Nombre libre',protocol:'prestashop',enabled:true,revision:2,verified_revision:2,real_data_authorized:true}));
assert.equal(registry.connection('hortimatic-2',profiles).id,records[2].connection_id);
assert.equal(storeConnection(profiles,'hortimatic-2',registry).id,records[2].connection_id);
assert.equal(prestashopStore('future-store',registry).name,'future-store');
assert.equal(productPhoto({id_default_image:'9'},'future-store',registry),registry.imageUrl('future-store',9));
assert.equal(productWebUrl({id:'7'},'hortimatic-2',registry),registry.productUrl('hortimatic-2',7));
assert.equal(prestashopProductImage('future-store',9,registry),registry.imageUrl('future-store',9));
assert.notEqual(registry.cacheKey('hortimatic',2,'products'),registry.cacheKey('hortimatic-2',2,'products'));
assert.equal(registry.productUrl('hortimatic-2',7),'https://hortimatic-2.example/index.php?controller=product&id_product=7');
assert.equal(registry.imageUrl('future-store',9),'https://future-store.example/9-home_default/product.jpg');
assert.throws(()=>registry.imageUrl('future-store','https://other.example/image.jpg'));
assert.throws(()=>registry.connection('hortimatic',[{...profiles[0],endpoint:'https://other.example/api/'}]));
assert.throws(()=>registry.connection('hortimatic-2',profiles.slice(0,2)));
assert.throws(()=>registry.connection('hortimatic',profiles.map(c=>({...c,verified_revision:1}))));
assert.throws(()=>registry.connection('hortimatic',[profiles[0],profiles[0]]));
assert.throws(()=>createWebsiteRegistry([...records,records[0]]));
assert.throws(()=>createWebsiteRegistry([site('bad',1,{origin:'https://user:secret@store.example'})]));
assert.throws(()=>createWebsiteRegistry([site('bad',1,{include_in_totals:undefined})]));
const retired=createWebsiteRegistry([site('old',1,{status:'retired'})]);
assert.equal(retired.get('old').name,'old');
assert.equal(retired.active().length,0);
assert.throws(()=>retired.connection('old',profiles));
assert.equal(registry.active().length,4); // another context cannot mutate this one
console.log('Website registry: four websites, explicit totals, lifecycle, connection and cache isolation passed.');
