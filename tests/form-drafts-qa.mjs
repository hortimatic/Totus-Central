 await page.locator('#exLineDesc_0').fill('Concepto de prueba');await page.locator('#exLineBase_0').fill('10');
 await page.evaluate(()=>{const client=window.supabase.createClient(),original=client.rpc;client.rpc=async(...args)=>{if(args[0]==='totus_save_expense')await new Promise(r=>setTimeout(r,250));return original(...args)}});
 await page.locator('[data-action="expense-save"]').first().dblclick();
