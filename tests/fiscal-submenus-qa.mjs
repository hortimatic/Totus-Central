import {clickModuleLink} from './ui-navigation.mjs';
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({locale:'es-ES',acceptDownloads:true});
const errors=[],steps=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',d=>d.accept(d.type()==='prompt'?'Motivo de corrección QA':undefined));
const data=()=>page.evaluate(()=>({
 settings:window.__mockDb.ops_business_settings[0],
 categories:window.__mockDb.ops_expense_categories,
 taxPayments:window.__mockDb.ops_tax_payments,
 adjustments:window.__mockDb.ops_fiscal_adjustments,
 manualIncome:window.__mockDb.ops_income_adjustments,
 audit:window.__mockDb.ops_audit_log
}));
const nav=async section=>{
 await clickModuleLink(page,page.locator('#nav [data-route="'+section+'"]'));
 await page.waitForTimeout(60);
};
try{
 await page.goto('http://127.0.0.1:4173/tests/app-mock.html',{waitUntil:'networkidle'});
 await nav('administracion');
 await page.locator('[data-action="admin-section"][data-section="fiscal"]').click();
 await page.locator('#cfgVat').fill('150,00');
 await page.locator('[data-action="config-save"]').click();
 assert.equal((await data()).settings.default_sales_vat_rate,21,'Un IVA fuera de rango se ha guardado');
 await page.locator('#cfgVat').fill('21');
 await page.locator('#cfgPurchaseRe').fill('5,20');
 await page.locator('#cfgIrpf').fill('20,00');
 await page.locator('#cfgDifficultCap').fill('2000,00');
 await page.locator('[data-action="config-save"]').click();
 let d=await data();
 assert.equal(d.settings.purchase_re_rate,5.2,'Se perdió el decimal en recargo');
 assert.equal(d.settings.irpf_prepayment_rate,20,'No se ha guardado el tipo del modelo 130');
 assert.equal(d.settings.difficult_expense_annual_cap,2000,'No se ha guardado el límite de difícil justificación');
 assert.equal(await page.locator('#cfgReta').count(),0,'No mostrar una simulación RETA que no interviene en los cálculos');
 steps.push('configuración fiscal:rechazo de rangos,decimales y persistencia');
 await page.locator('[data-action="expense-category-new"]').click();
 await page.locator('#ecCode').fill('QA_TEST');
 await page.locator('#ecName').fill('Prueba fiscal QA');
 await page.locator('#ecManager').fill('45');
 await page.locator('#ecAeat').fill('B');
 await page.locator('[data-action="expense-category-save"]').click();
 d=await data();
 let category=d.categories.find(x=>x.code==='QA_TEST');
 assert(category?.manager_code==='45','No se guardó el código gestoría de la categoría');
 assert.equal(category.aeat_group,'B');
 await page.locator('[data-action="expense-category-edit"][data-id="'+category.id+'"]').click();
 await page.locator('#ecName').fill('Categoría fiscal QA modificada');
 await page.locator('#ecActive').uncheck();
 await page.locator('[data-action="expense-category-save"]').click();
 d=await data();
 category=d.categories.find(x=>x.id===category.id);
 assert.equal(category.name,'Categoría fiscal QA modificada');
 assert.equal(category.active,false);
 await page.locator('[data-action="expense-category-new"]').click();
 await page.locator('#ecCode').fill('QA_TEST');
 await page.locator('#ecName').fill('Duplicada');
 await page.locator('[data-action="expense-category-save"]').click();
 assert.equal((await data()).categories.filter(x=>x.code==='QA_TEST').length,1,'Categoría duplicada aceptada');
 await page.locator('#modalHost .close-btn').click();
 await page.getByRole('heading',{name:'Cambios sin guardar',exact:true}).waitFor();await page.locator('[data-confirm="accept"]').click();
 steps.push('categorías:crear,editar,desactivar,rechazar código duplicado');
 await nav('fiscalidad');
 await page.locator('[data-action="tax-payment-edit"][data-model="130"]').first().click();
 await page.locator('#txAmount').fill('-20');
 await page.locator('[data-action="tax-payment-save"]').click();
 assert.equal((await data()).taxPayments.length,0,'Pago fiscal negativo ha sido guardado');
 await page.locator('#txAmount').fill('2175,69');
 await page.locator('#txDate').fill('2026-10-16');
 await page.locator('[data-action="tax-payment-save"]').click();
 d=await data();
 const item=d.taxPayments.find(x=>x.tax_type==='130');
 assert(item&&item.amount===2175.69,'No se guardó el pago de modelo 130');
 await page.locator('[data-action="tax-payment-edit"][data-model="130"]').first().click();
 await page.locator('#txAmount').fill('2250,30');
 await page.locator('[data-action="tax-payment-save"]').click();
 d=await data();
 assert.equal(d.taxPayments.find(x=>x.id===item.id)?.amount,2250.30,'Edición fiscal no persiste');
 assert.equal(d.taxPayments.find(x=>x.id===item.id)?.created_by,item.created_by,'Editar alteró autor original');
 await page.locator('[data-action="tax-payment-edit"][data-model="130"]').first().click();
 await page.locator('[data-action="tax-payment-delete"]').click();
 assert.equal((await data()).taxPayments.length,0,'No se eliminó pago fiscal');
 steps.push('modelo 130:rechazo negativo,alta,edición,autor,baja');
 await page.locator('[data-action="fiscal-adjustment-new"]').first().click();
 await page.locator('#faDescription').fill('Prueba fiscal de ajuste');
 await page.locator('#faAmount').fill('-5');
 await page.locator('[data-action="fiscal-adjustment-save"]').click();
 assert.equal((await data()).adjustments.length,0,'Ajuste negativo aceptado');
 await page.locator('#faAmount').fill('120,50');
 await page.locator('[data-action="fiscal-adjustment-save"]').click();
 d=await data();
 const adjustment=d.adjustments.find(x=>x.description==='Prueba fiscal de ajuste');
 assert(adjustment&&adjustment.amount===120.50,'Ajuste fiscal no persistió');
 await page.locator('[data-action="fiscal-adjustment-edit"][data-id="'+adjustment.id+'"]').click();
 await page.locator('#faDescription').fill('Ajuste revisado');
 await page.locator('[data-action="fiscal-adjustment-save"]').click();
 d=await data();
 assert.equal(d.adjustments.find(x=>x.id===adjustment.id).description,'Ajuste revisado');
 assert.equal(d.adjustments.find(x=>x.id===adjustment.id).created_by,adjustment.created_by,'Editando ajuste se sobrescribió autor');
 await page.locator('[data-action="fiscal-adjustment-edit"][data-id="'+adjustment.id+'"]').click();
 await page.locator('[data-action="fiscal-adjustment-delete"]').click();
 assert.equal((await data()).adjustments.length,0,'No se eliminó ajuste');
 steps.push('ajustes:filtro negativo,crear,editar,eliminar');
 await nav('fiscalidad');
 await page.locator('[data-action="income-adjustment-new"]').click();
 await page.locator('#iaConcept').fill('Venta complementaria QA');
 await page.locator('#iaAmount').fill('37,75');
 await page.locator('[data-action="income-adjustment-save"]').click();
 let incomes=(await data()).manualIncome;
 const entry=incomes.find(x=>x.concept==='Venta complementaria QA');
 assert(entry&&entry.amount===37.75,'Ingreso manual no creado');
 await page.locator('[data-action="income-adjustment-edit"][data-id="'+entry.id+'"]').click();
 await page.locator('#iaAmount').fill('42,50');
 await page.locator('[data-action="income-adjustment-save"]').click();
 assert((await data()).manualIncome.some(x=>x.id===entry.id&&x.amount===42.5),'Edición del ingreso manual falló');
 await page.locator('[data-action="income-adjustment-delete"][data-id="'+entry.id+'"]').click();
 await page.waitForTimeout(60);
 assert(!(await data()).manualIncome.some(x=>x.id===entry.id),'El ingreso manual no se eliminó');
 const proof=(await data()).audit.find(x=>x.entity_id===entry.id&&x.action==='eliminar_ingreso_manual');
 assert(proof?.detail?.motivo==='Motivo de corrección QA','La baja no ha registrado su motivo en el Log');
 steps.push('ingresos manuales: crear,editar,eliminar con motivo auditado');
 assert(!errors.length,errors.join('; '));
 console.log('FISCAL SUBMENUS QA: '+steps.join(' | ')+' OK');
}finally{await browser.close()}
