import assert from 'node:assert/strict';
import {editableReferences,expenseStoreSelection,reportDiaryStores,reportDiaryStore} from '../src/reference-options.js';
import {state} from '../src/state.js';
import {closingRecordHtml,expenseRecordHtml,invoiceRecordHtml} from '../src/pages/main.js';
const rows=[{id:'a',name:'Activa',active:true},{id:'b',name:'Anterior',active:false},{id:'c',name:'Otra anterior',active:false}];
assert.deepEqual(editableReferences(rows).map(x=>x.id),['a']);
assert.deepEqual(editableReferences(rows,'b').map(x=>x.id),['a','b']);
assert.deepEqual(editableReferences(rows,['b','c']).map(x=>x.id),['a','b','c']);
assert.equal(expenseStoreSelection(null,rows),'a');
assert.equal(expenseStoreSelection({store_id:null},rows),'');
assert.equal(expenseStoreSelection({store_id:'b'},rows),'b');
assert.equal(expenseStoreSelection(null,rows,true),'');
assert.equal(reportDiaryStores(rows,[]).length,3);
assert.equal(reportDiaryStores(rows,[{store_id:null}]).at(-1).id,null);
assert.equal(reportDiaryStore(rows,'__common__').id,null);
assert.equal(reportDiaryStore(rows,'b').name,'Anterior');
state.user={role:'admin'};state.session={user:{id:'user'}};state.data.settings={};
state.data.stores=rows;state.data.drawers=[{id:'old-drawer',store_id:'b',name:'Caja anterior',active:false}];
state.data.closingDrawers=[{id:'detail',closing_id:'close',drawer_id:'old-drawer',opening_cash:50,closing_cash:60,card_sales:20}];
const close=closingRecordHtml({id:'close',store_id:'b',business_date:'2026-01-02',status:'cerrado'});
assert(close.includes('Caja anterior'));assert(close.includes('value="b" selected'));
assert(!closingRecordHtml().includes('Caja anterior'));
const expense=expenseRecordHtml({id:'expense',store_id:null,supplier_name:'Proveedor común',document_kind:'factura'});
assert(/id="exStore"[\s\S]*?<option value="" selected/.test(expense));
state.data.series=[{id:'old-series',active:false,store_id:'b',year:2026,document_type:'factura',series_kind:'invoice',code:'OLD'}];
state.data.templates=[{id:'old-template',active:false,store_id:'b',name:'Plantilla anterior'}];
state.data.customers=[{id:'old-customer',active:false,name:'Cliente anterior'}];
const invoice=invoiceRecordHtml({id:'invoice',status:'borrador',store_id:'b',issue_date:'2026-01-02',series_id:'old-series',template_id:'old-template',customer_id:'old-customer'});
for(const id of ['b','old-series','old-template','old-customer'])assert(invoice.includes('value="'+id+'" selected'),id);
console.log('REFERENCE OPTIONS QA: inactive linked records retained, common expense preserved, historic drawers visible, new records exclude inactive references');
