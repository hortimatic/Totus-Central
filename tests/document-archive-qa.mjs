import assert from 'node:assert/strict';
import {uniqueArchiveDocumentPath} from '../src/file-utils.js';
const used=new Set();
const first={id:'11111111-1111-4111-8111-111111111111',doc_type:'factura_recibida',supplier_or_customer:'Proveedor A',original_name:'factura.pdf'};
const second={...first,id:'22222222-2222-4222-8222-222222222222'};
const third={...second,id:'33333333-3333-4333-8333-333333333333'};
const a=uniqueArchiveDocumentPath(first,used);
const b=uniqueArchiveDocumentPath(second,used);
const c=uniqueArchiveDocumentPath(third,used);
assert.equal(a,'factura_recibida/Proveedor_A/factura.pdf');
assert.ok(b.endsWith('factura__22222222-2222-4222-8222-222222222222.pdf'));
assert.ok(c.endsWith('factura__33333333-3333-4333-8333-333333333333.pdf'));
assert.equal(used.size,3,'No deben sobrescribirse facturas con el mismo nombre');
const unicode=uniqueArchiveDocumentPath({...first,id:'00001',original_name:'fáctura.pdf'},used);
assert.notEqual(unicode,a,'Los nombres distintos que se normalizan igual también deben protegerse');
assert.equal(used.size,4);
const repeated=uniqueArchiveDocumentPath(second,used);
assert.notEqual(repeated,b,'La misma entrada no debe reutilizar una ruta ya ocupada');
assert.ok(![a,b,c,unicode].includes(repeated));
console.log('DOCUMENT ARCHIVE QA: nombres homónimos, colisiones por acentos, índice único OK');
