import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({acceptDownloads:true,locale:'es-ES'});
const errors=[],done=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',d=>d.accept());
const state=()=>page.evaluate(()=>({
 customers:window.__mockDb.ops_customers,
 templates:window.__mockDb.ops_document_templates,
 series:window.__mockDb.ops_invoice_series,
 files:[...window.__mockUploads.keys()]
}));
const tab=async section=>{
 await page.locator('[data-action="billing-section"][data-section="'+section+'"]').first().click();
 assert((await page.locator('#content h2').allTextContents()).some(x=>x.toLocaleLowerCase('es').includes(section==='plantillas'?'plantillas':section)),'No se abre '+section);
};
try{
 await page.goto('http://127.0.0.1:4173/tests/app-mock.html',{waitUntil:'networkidle'});
 await page.locator('#nav [data-route="facturacion"]').click();
 await tab('clientes');
 await page.locator('[data-action="customer-new"]').click();
 await page.locator('#cuName').fill('Cliente de prueba QA');
 await page.locator('#cuTax').fill('B98765432');
 await page.locator('#cuEmail').fill('cliente.qa@example.com');
 await page.locator('#cuPayment').selectOption('bizum');
 await page.locator('[data-action="customer-save"]').click();
 assert((await state()).customers.some(x=>x.tax_id==='B98765432'&&x.default_payment_method==='bizum'),'Alta de cliente no persiste');
 await page.locator('[data-action="customer-edit"]').first().click();
 await page.locator('#cuName').fill('Cliente QA editado');
 await page.locator('[data-action="customer-save"]').click();
 assert((await state()).customers[0].name==='Cliente QA editado','Edición cliente no persiste');
 await page.locator('[data-action="customer-edit"]').first().click();
 await page.locator('[data-action="customer-delete"]').click();
 assert(!(await state()).customers.length,'No se eliminó cliente desde su ficha');
 done.push('clientes:alta,edición,baja');
 await tab('plantillas');
 const oldCount=(await state()).files.length;
 await page.locator('[data-action="template-new"]').click();
 const image=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLttAAAAABJRU5ErkJggg==','base64');
 await page.locator('#tpLogo').setInputFiles({name:'logo-qa.png',mimeType:'image/png',buffer:image});
 await page.locator('[data-action="template-save"]').click();
 assert((await state()).files.length===oldCount,'El formulario inválido ha subido el logo antes de validar');
 assert(!(await state()).templates.some(x=>x.name==='Logo QA'),'Se guardó una plantilla sin nombre');
 await page.locator('#tpName').fill('Logo QA');
 await page.locator('#tpCode').fill('LOGO_QA');
 await page.locator('#tpDefaultInvoice').check();
 await page.locator('[data-action="template-save"]').click();
 let snap=await state();
 let original=snap.templates.find(x=>x.code==='LOGO_QA');
 assert(original?.logo_path&&original.default_invoice,'Plantilla/logo o defecto no guardados correctamente');
 assert(snap.files.includes('business-assets/'+original.logo_path),'El logo no se subió al guardar');
 assert(!snap.templates.some(x=>x.id!==original.id&&x.default_invoice&&x.store_id==null),'No se cambió la plantilla predeterminada anterior');
 await page.locator('[data-action="template-preview"][data-id="'+original.id+'"]').click();
 assert((await page.locator('#modalHost').innerText()).includes('Ejemplo de concepto o producto'),'Vista previa de plantilla sin concepto de prueba');
 await page.locator('#modalHost .close-btn').click();
 done.push('plantillas:validación previa,logo,valor predeterminado,vista previa');
 await page.locator('[data-action="template-edit"][data-id="'+original.id+'"]').click();
 await page.locator('[data-action="template-duplicate"]').click();
 snap=await state();
 const duplicate=snap.templates.find(x=>x.code==='LOGO_QA-COPIA');
 assert(duplicate?.logo_path===original.logo_path&&duplicate.default_invoice===false,'Duplicar plantilla no conserva logo ni desactiva valor por defecto');
 await page.locator('[data-action="template-delete"][data-id="'+original.id+'"]').click();
 snap=await state();
 assert(!snap.templates.some(x=>x.id===original.id),'Original no eliminado');
 assert(snap.files.includes('business-assets/'+duplicate.logo_path),'Eliminar original borró logo compartido de la copia');
 done.push('plantillas:duplicación y borrado con logo compartido');
 await page.locator('[data-action="template-edit"][data-id="'+duplicate.id+'"]').click();
 const newImage=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLttAAAAABJRU5ErkJggg==','base64');
 await page.locator('#tpLogo').setInputFiles({name:'logo-sustituto.png',mimeType:'image/png',buffer:newImage});
 await page.locator('#tpDefaultInvoice').check();
 await page.locator('[data-action="template-save"]').click();
 snap=await state();
 const changed=snap.templates.find(x=>x.id===duplicate.id);
 assert(changed?.logo_path&&changed.logo_path!==duplicate.logo_path,'No se reemplazó el logo');
 assert(changed.default_invoice,'Una plantilla nueva no puede desactivar su propio valor predeterminado');
 assert(!snap.files.includes('business-assets/'+duplicate.logo_path),'Quedó logo anterior huérfano');
 assert(snap.files.includes('business-assets/'+changed.logo_path),'El logo actualizado no se almacenó');
 await page.locator('[data-action="template-delete"][data-id="'+changed.id+'"]').click();
 snap=await state();
 assert(!snap.files.includes('business-assets/'+changed.logo_path),'Eliminar última plantilla dejó logo huérfano');
 done.push('plantillas:reemplazo,limpieza y borrado completo');
 await tab('series');
 const initial=(await state()).series.length;
 await page.locator('[data-action="series-new"]').click();
 await page.locator('#srStore').selectOption({index:1});
 await page.locator('#srYear').fill('2026');
 await page.locator('#srCode').fill('QA_BILLING_2026');
 await page.locator('#srPrefix').fill('QAB-');
 await page.locator('#srPadding').fill('5');
 await page.locator('[data-action="series-save"]').click();
 snap=await state();
 let series=snap.series.find(x=>x.code==='QA_BILLING_2026');
 assert(snap.series.length===initial+1&&series?.padding===5,'Serie nueva no persistió');
 await page.locator('[data-action="series-edit"][data-id="'+series.id+'"]').click();
 await page.locator('#srNext').fill('22');
 await page.locator('[data-action="series-save"]').click();
 snap=await state();
 assert(snap.series.find(x=>x.id===series.id)?.next_number===22,'No se editó siguiente número');
 await page.locator('[data-action="series-toggle"][data-id="'+series.id+'"]').click();
 snap=await state();
 assert(snap.series.find(x=>x.id===series.id)?.active===false,'No se desactivó serie');
 await page.locator('[data-action="series-new"]').click();
 await page.locator('#srYear').fill('2026');
 await page.locator('#srCode').fill('QA_BILLING_2026');
 await page.locator('#srPrefix').fill('OTHER-');
 await page.locator('[data-action="series-save"]').click();
 assert((await state()).series.length===initial+1,'Se permitió crear serie duplicada para un año');
 done.push('series:alta,edición,activación y rechazo de duplicados');
 assert(errors.length===0,'Errores JavaScript: '+errors.join('; '));
 console.log('BILLING SUBMENUS QA: '+done.join(' | ')+' OK');
}finally{await browser.close()}
