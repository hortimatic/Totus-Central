import assert from 'node:assert/strict';
import {parseVariantAttributes,formatVariantAttributes,variantStudy,numericRange,validateVariant} from '../src/pricing-core.js';
const attrs=parseVariantAttributes('Color: Negro; Resistencia: 0,8 Ω\nNicotina: 10 mg');
assert.deepEqual(attrs,{Color:'Negro',Resistencia:'0,8 Ω',Nicotina:'10 mg'});
assert.deepEqual(parseVariantAttributes(formatVariantAttributes(attrs)),attrs);
assert.throws(()=>parseVariantAttributes('__proto__: peligro'));
assert.throws(()=>parseVariantAttributes('Color: Azul; Color: Negro'));
assert.throws(()=>parseVariantAttributes('sin separador'));
const base={name:'Sales 10 mg',sku:'DEMO-10',cost_net:3.2,pvp:5.7};
const ten=variantStudy(base),twenty=variantStudy({...base,cost_net:3.7,pvp:6.3});
assert.ok(Math.abs(ten.costReal-4.0384)<1e-10);
assert.ok(Math.abs(ten.margin-1.6616)<1e-10);
assert.ok(Math.abs(twenty.margin-1.6306)<1e-10);
assert.notEqual(twenty.margin,ten.margin,'Different nicotine prices must have independent margins');
assert.equal(variantStudy({...base,cost_net:null}),null);
assert.equal(variantStudy({...base,pvp:''}),null);
assert.equal(variantStudy({...base,cost_net:-1}),null);
assert.equal(variantStudy({...base,cost_net:0}).costReal,0);
assert.equal(variantStudy({...base,special_tax_amount:100}).costReal,ten.costReal,'Informative excise must not be added twice');
assert.equal(numericRange([null,5.7,6.3],n=>n.toFixed(2)),'5.70 – 6.30');
assert.equal(numericRange([null],String),'—');
assert.equal(numericRange([0,0],String),'0');
assert.throws(()=>validateVariant({...base,cost_net:-1}));
assert.throws(()=>validateVariant(base,[{id:'other',sku:'demo-10'}]));
assert.equal(validateVariant(base,[{id:'self',sku:'demo-10'}],'self'),base);
console.log('PRICING VARIANTS: attributes, costs, nicotine-specific prices, unknown vs zero, duplicate SKU, informative tax and ranges OK');
