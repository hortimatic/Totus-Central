import assert from 'node:assert/strict';
import {defaultRolePermissions,rolePermissions,setRolePermissions,permissionsFor,canUser,PERMISSION_MODULES} from '../src/permissions.js';
import {formField,selectField} from '../src/components.js';
import {administracion} from '../src/pages/main.js';
import {state} from '../src/state.js';
const admin={role:'admin',email:'admin@qa.invalid'};
const manager={role:'gerente',email:'gerente@qa.invalid'};
const staff={role:'encargado',email:'staff@qa.invalid'};
assert.equal(PERMISSION_MODULES.length,9);
assert.equal(defaultRolePermissions('encargado','gastos').delete,false);
assert.equal(defaultRolePermissions('gerente','gastos').create,true);
const baseline=defaultRolePermissions('gerente','gastos');
assert.equal(baseline.view,true);
setRolePermissions([{role:'gerente',module:'gastos',can_view:true,can_create:false,can_edit:false,can_delete:false,can_export:true}]);
assert.equal(canUser(manager,'gastos','create',[]),false,'El rol debe desactivar crear en front');
assert.equal(canUser(manager,'gastos','export',[]),true);
assert.equal(canUser(admin,'gastos','delete',[]),true,'El admin no se configura');
assert.equal(canUser(manager,'gastos','create',[{email:'gerente@qa.invalid',module:'gastos',can_view:true,can_create:true,can_edit:false,can_delete:false,can_export:false}]),true,'Excepción de usuario prevalece');
assert.equal(permissionsFor(manager,'gastos',[]).view,true);
setRolePermissions([]);
assert.equal(rolePermissions('gerente','gastos').create,true,'El restablecimiento recupera ajustes predeterminados');
for(const [module] of PERMISSION_MODULES){
 const html=formField('Rol','role_'+module);
 assert.match(html,/<details class="field-help">/);
 assert.match(html,/<summary[^>]*>i<\/summary>/);
 assert.match(html,/Conjunto de permisos iniciales/);
}
assert.match(selectField('IVA (%)','vat',[{value:21,label:'21 %'}],21),/<details class="field-help">/);
assert.match(formField('Un campo nuevo','newField'),/<details class="field-help">/);
state.user=admin;
state.data.roles=[{code:'admin',name:'Administrador',is_system:true,sort_order:0},{code:'gerente',name:'Gerencia',is_system:true,sort_order:10},{code:'encargado',name:'Encargado',is_system:true,sort_order:20}];
state.data.team=[];
state.data.rolePermissions=[];
state.data.userPermissions=[];
state.views.administracion={section:'roles'};
const html=administracion();
assert.ok(html.includes('Roles y permisos'),'La pestaña de roles debe ser visible');
assert.ok(html.includes('Editar permisos del rol'),'Debe poder editar los roles');
assert.ok(html.includes('Gerencia')&&html.includes('Encargado'),'Los roles deben estar separados');
assert.ok(!html.includes('data-role="admin"'),'No permitir editar al administrador');
console.log('ROLES & HELP QA: rol configurable, excepciones, 9 módulos y ayudas i OK');
